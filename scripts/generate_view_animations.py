"""Writes the held-pose inspect animations (view-animations / view-pools) into inspect.yml.

Every animation starts and ends in the first-person hold. Groups (see ViewInspect):
  weapon  move = hand travel in view space (blocks); rotate = wrist turn about the grip
          (x along blade/barrel, y up the artwork, z out of the flat side)
  elbow   move = extra elbow travel; the shoulder already follows the hand
  grip    move x = main hand lets go (tosses), y = support hand lets go
  support move = support hand slides along the weapon (canvas units)
  rig layers (mechanism, blade, handle_a, handle_b): move = slide along the weapon (canvas units),
          rotate = turn about the layer's joint (HeldRig.hinge); slides, bolts, pumps, butterfly
          handles and folding blades move on their own while the rest of the rig stays in the hand
Other players see the same wrist turns in the crossbow hold at the model's hand (ViewInspect.sampleBody).
"""
