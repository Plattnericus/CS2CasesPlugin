def key(ticks, move=None, rotate=None, ease='inout'):
    if isinstance(rotate, str):
        rotate, ease = None, rotate
    return dict(ticks=ticks, move=move, rotate=rotate, ease=ease)


def scaled(frames, speed=1.0, amplitude=1.0):
    out = []
    for f in frames:
        g = dict(f)
        g['ticks'] = max(1, round(f['ticks'] * speed)) if f['ticks'] else 0
        if f['rotate'] is not None:
            g['rotate'] = [round(v * amplitude, 2) for v in f['rotate']]
        if f['move'] is not None:
            g['move'] = [round(v * (0.6 + 0.4 * amplitude), 3) for v in f['move']]
        out.append(g)
    return out


# Groups that keep their exact values in every family: hand releases and rig layer motions.
EXACT = {'grip', 'mechanism', 'blade', 'handle_a', 'handle_b'}


def animation(weapon, elbow=None, grip=None, support=None, sounds=None, speed=1.0, amplitude=1.0, parts=None):
    groups = {'weapon': scaled(weapon, speed, amplitude)}
    for name, frames in [('elbow', elbow), ('grip', grip), ('support', support)] + list((parts or {}).items()):
        if frames:
            groups[name] = scaled(frames, speed, 1.0 if name in EXACT else amplitude)
    return dict(groups=groups, sounds={round(t * speed): s for t, s in (sounds or {}).items()})


