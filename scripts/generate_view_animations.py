def vector(v):
    return '[' + ', '.join(f'{x:g}' for x in v) + ']'


def emit():
    lines = [BEGIN, '# Held-pose inspects: the weapon starts and ends in your first-person hold and your skin arms',
             '# follow it (wrist, elbow, shoulder, second hand). Units: blocks and degrees; see ViewInspect.',
             'view-animations:']
    pools = {}
    for family, (prefix, moves, speed, amplitude) in FAMILIES.items():
        pools[family] = []
        for name, base in moves.items():
            anim_id = f'{prefix}_{name}'
            pools[family].append(anim_id)
            a = {g: scaled(frames, speed, 1.0 if g in EXACT else amplitude) for g, frames in base['groups'].items()}
            lines.append(f'  {anim_id}:')
            if base['sounds']:
                lines.append('    sounds:')
                for tick, sound in sorted(base['sounds'].items()):
                    lines.append(f"      '{round(tick * speed)}': {sound}")
            lines.append('    groups:')
            for group, frames in a.items():
                lines.append(f'      {group}:')
                lines.append('        keyframes:')
                for f in frames:
                    parts = [f"ticks: {f['ticks']}"]
                    if f['move'] is not None: parts.append('move: ' + vector(f['move']))
                    if f['rotate'] is not None: parts.append('rotate: ' + vector(f['rotate']))
                    parts.append('ease: ' + f['ease'])
                    lines.append('        - {' + ', '.join(parts) + '}')
    weapon_pools = {}

    def special(anim_id, base, speed, amplitude):
        a = {g: scaled(frames, speed, 1.0 if g in EXACT else amplitude) for g, frames in base['groups'].items()}
        lines.append(f'  {anim_id}:')
        lines.append('    sounds:')
        for tick, sound in sorted(base['sounds'].items()):
            lines.append(f"      '{round(tick * speed)}': {sound}")
        lines.append('    groups:')
        for group, frames in a.items():
            lines.append(f'      {group}:')
            lines.append('        keyframes:')
            for f in frames:
                parts = [f"ticks: {f['ticks']}"]
                if f['move'] is not None: parts.append('move: ' + vector(f['move']))
                if f['rotate'] is not None: parts.append('rotate: ' + vector(f['rotate']))
                parts.append('ease: ' + f['ease'])
                lines.append('        - {' + ', '.join(parts) + '}')

    for anim_id, (base, speed, amplitude, family, weapons) in SPECIAL.items():
        special(anim_id, base, speed, amplitude)
        for weapon in weapons:
            weapon_pools[weapon] = pools[family] + [anim_id]
    for anim_id, (base, speed, amplitude, family, weapons) in SPECIAL_BOLT.items():
        special(anim_id, base, speed, amplitude)
        for weapon in weapons:
            weapon_pools[weapon] = [anim_id if a == f'{family}_bolt' else a for a in pools[family]]
    lines.append('view-pools:')
    for family, ids in list(pools.items()) + list(weapon_pools.items()):
        lines.append(f'  {family}: [' + ', '.join(ids) + ']')
    lines.append(END)
    return '\n'.join(lines) + '\n'


def main():
    text = TARGET.read_text()
    block = emit()
    if BEGIN in text:
        start, end = text.index(BEGIN), text.index(END) + len(END) + 1
        text = text[:start] + block + text[end:]
    else:
        text = text.replace('\nanimations:\n', '\n' + block + 'animations:\n', 1)
    TARGET.write_text(text)
    print('wrote', TARGET, block.count('\n  ') , 'lines')


if __name__ == '__main__':
    main()
